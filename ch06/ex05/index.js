// 次の条件を満たすオブジェクトを作成し、for/in ループで順番を確認する
//
// - 以下のプロパティを持つオブジェクトをプロトタイプとして持つ
//   - プロパティ名が数値のプロパティ
//   - プロパティ名が文字列のプロパティ
//   - 列挙可能なプロパティ
// - 以下のプロパティを持つ
//   - プロパティ名が数値かつプロトタイプの数値プロパティと同名のプロパティ
//   - プロパティ名が数値かつプロトタイプの数値プロパティと同名でないプロパティ
//   - プロパティ名が文字列かつプロトタイプの文字列プロパティと同名のプロパティ
//   - プロパティ名が文字列かつプロトタイプの文字列プロパティと同名でないプロパティ
//   - 列挙不可かつプロトタイプの列挙可能プロパティと同名のプロパティ

// プロトタイプオブジェクト。
// オブジェクトリテラルで定義したプロパティはデフォルトで全て列挙可能(enumerable: true)になるので、
// これだけで「数値名のプロパティ(1)」「文字列名のプロパティ(str)」「列挙可能なプロパティ」の
// 3条件を同時に満たしている。
const parent = { 1: "num", str: "str", enum: "enum" };

// parentをプロトタイプとして持つ、新しい空のオブジェクト
const child = Object.create(parent);

// 数値名のプロパティを2つ追加する。
// プロパティ名として数値を書くときはドット記法(child.1のような書き方)は使えないため、
// ブラケット記法(child[1])で書く。
child[1] = "num_override"; // parentの数値プロパティ(1)と同名 → 上書き(shadowing)する形になる
child[2] = "num2"; // parentには存在しない数値名 → child独自のプロパティ

// 文字列名のプロパティを2つ追加する
child.str = "str_override"; // parentの文字列プロパティ(str)と同名 → 上書き(shadowing)する形になる
child.str2 = "str2"; // parentには存在しない文字列名 → child独自のプロパティ

// parentの列挙可能なプロパティ(enum)と同名だが、あえて列挙不可(enumerable: false)にして追加する。
// オブジェクトリテラルでは列挙不可のプロパティを作れないため、Object.defineProperty()を使う。
Object.defineProperty(child, "enum", {
  value: "enum_override",
  enumerable: false,
});

// for/in ループは、自分自身(own property)の列挙可能なプロパティ → プロトタイプの列挙可能なプロパティ、
// という順に辿っていく。ただし、一度でも同じプロパティ名がown propertyとして存在していれば、
// たとえそれが列挙不可であっても、その名前でプロトタイプ側を探しに行くことはない(名前が「消費」される)。
//
// そのため、enumはchild自身に列挙不可のプロパティとして存在している時点で、
// parent.enum(列挙可能)があってもfor/inには一切出てこないはずである。
//
// 実行結果:
// 1：num_override
// 2：num2
// str：str_override
// str2：str2
// (↑ enumはどの行にも出てこない。列挙不可の自プロパティが同名のプロトタイプの
//    列挙可能プロパティを完全に覆い隠すことが確認できた)
for (const key in child) {
  console.log(key + "：" + child[key]);
}
