// 2次元配列を行列として扱い、行列の加算・乗算を行う関数を作成する。
// 加算・乗算が定義できないサイズの行列が渡された場合はエラーを投げる。
//
// 行列は「配列の配列」で表す。例: [[1, 2, 3], [4, 5, 6]] は 2行3列の行列。
//   - 行数: a.length
//   - 列数: a[0].length(1行目の長さ。どの行も同じ長さである前提)
//   - i 行 j 列の要素: a[i][j]

// 行列の加算: 同じサイズの行列 a, b を足した行列を返す。
//
// 例:
//   [[1, 2],     [[5, 6],       [[ 6,  8],
//    [3, 4]]  +   [7, 8]]   =    [10, 12]]
//   同じ位置の要素どうしを足す(結果[i][j] = a[i][j] + b[i][j])。
export function add(a, b) {
  // 加算が定義できるのは、行数も列数も同じときだけ。
  // 違うサイズのまま計算すると、b[i][j] が undefined になって NaN の入った行列が返ってしまい、
  // エラーにならずに間違った結果が返る(気づきにくい不具合になる)ので、先にエラーを投げる。
  if (a.length !== b.length || a[0].length !== b[0].length) {
    throw new Error("行列のサイズが一致しない");
  }

  // 結果を入れる配列。a や b は書き換えず、新しい配列を作って返す。
  const result = [];
  for (let i = 0; i < a.length; i++) {
    // 結果の i 行目用の空の配列を用意する。
    // これがないと result[i] が undefined のままで、result[i][j] = ... でエラーになる。
    // (JavaScript には「サイズを指定して2次元配列を宣言する」書き方はなく、
    //  空の配列に行ごとの配列を足していく)
    result[i] = [];
    for (let j = 0; j < a[0].length; j++) {
      // 同じ位置(i 行 j 列)の要素どうしを足す。
      result[i][j] = a[i][j] + b[i][j];
    }
  }

  return result;
}

// 行列の乗算: a(m行n列) と b(n行p列) を掛けた行列(m行p列)を返す。
//
// 結果[i][j] は、「a の i 行目」と「b の j 列目」の、対応する要素どうしを掛けて全部足した値。
//
// 例(2行3列 × 3行2列 → 2行2列):
//   [[1, 2, 3],     [[ 7,  8],       [[ 58,  64],
//    [4, 5, 6]]  ×   [ 9, 10],    =   [139, 154]]
//                    [11, 12]]
//   結果[0][0] = 1*7 + 2*9 + 3*11 = 58   (a の 0 行目 × b の 0 列目)
//   結果[0][1] = 1*8 + 2*10 + 3*12 = 64  (a の 0 行目 × b の 1 列目)
//   結果[1][0] = 4*7 + 5*9 + 6*11 = 139  (a の 1 行目 × b の 0 列目)
//   結果[1][1] = 4*8 + 5*10 + 6*12 = 154 (a の 1 行目 × b の 1 列目)
export function multiply(a, b) {
  // 乗算が定義できるのは、a の列数(n)と b の行数(n)が同じときだけ。
  // 条件はこれだけで、a の行数と b の列数が同じである必要はない
  // (一致が必要なのは「掛け合わせる要素の個数」で、結果の行数・列数は a の行数と b の列数で決まる)。
  if (a[0].length !== b.length) {
    throw new Error("行列のサイズが一致しない");
  }

  const result = [];
  // i: 結果の行(0 〜 a の行数 - 1)
  for (let i = 0; i < a.length; i++) {
    result[i] = [];
    // j: 結果の列(0 〜 b の列数 - 1)。結果の列数は a ではなく b の列数になることに注意。
    for (let j = 0; j < b[0].length; j++) {
      // 結果[i][j] の合計。k のループに入る前に 0 から始める。
      // (最初から result[i][j] に += すると、初期値が undefined なので NaN になる)
      let sum = 0;
      // k: 掛け合わせる要素の順番(0 〜 n - 1。a の列数 = b の行数)。
      // a の i 行目の k 番目(a[i][k])と、b の j 列目の k 番目(b[k][j])を掛けて足す。
      for (let k = 0; k < a[0].length; k++) {
        sum += a[i][k] * b[k][j];
      }
      result[i][j] = sum;
    }
  }

  return result;
}
