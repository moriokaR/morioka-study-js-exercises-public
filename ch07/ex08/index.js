// 文字列の書記素を反転させる関数 reverse(str) を実装する。
// 例: "家族 👨‍👨‍👧‍👧" を渡すと "👨‍👨‍👧‍👧 族家" を返す。
// テストは、公開されているテスト (index.test.js) を使う。

// reverse(str): 文字列を、「見た目1文字」(書記素)の単位で、逆順にして返す。
//
// なぜ str.split("").reverse().join("") ではダメなのか(2段階ある):
//   1. split("") は、UTF-16 の1つ分(コードユニット)で分ける。
//      "𠮷" や多くの絵文字は、コードユニット2つ分(サロゲートペア)でできているので、
//      ばらばらに引き離されて、逆順にすると壊れた文字になる。
//        "𠮷".length // => 2
//   2. スプレッド [...str] は、コードポイント単位で分けるので、"𠮷" は1つとして扱える。
//      ところが "👨‍👨‍👧‍👧" は、👨 ZWJ 👨 ZWJ 👧 ZWJ 👧 の7つの部品でできている
//      (ZWJ = ゼロ幅接合子。見えない結合用の文字)。
//      7つに分けて逆順にすると、4人の並びが逆になった別の絵文字になる。
//        [..."👨‍👨‍👧‍👧"].length // => 7
//
// そこで Intl.Segmenter を使う。「見た目1文字」の単位(書記素)で分けてくれる。
//   new Intl.Segmenter()      ... 分割する道具を作る
//   .segment(str)             ... 書記素ごとに分けた結果(配列ではなく、イテラブル)を返す
//   [...結果]                 ... 配列にする。要素は { segment, index, input } のオブジェクト
//   .map((x) => x.segment)    ... オブジェクトから、文字(segment)だけを取り出す
//   .reverse().join("")       ... 逆順にして、区切りなしで1つの文字列につなげる
//   (map を忘れると、オブジェクトが "[object Object]" になってつながってしまう)
// 例: "家族 👨‍👨‍👧‍👧" は ["家", "族", " ", "👨‍👨‍👧‍👧"] の4つに分かれる。
export function reverse(str) {
  const segmenter = new Intl.Segmenter();
  const result = segmenter.segment(str);

  return [...result]
    .map((x) => x.segment)
    .reverse()
    .join("");
}
